def flag_code(value):
    """The ISO code ('DE') for a TS.Flag value, or None (no flag, or none exists)."""
    if not isinstance(value, int) or not 0 < value < len(FLAGS):
        return None
    return FLAGS[value][1]


def flag_name(value):
    """TSU's name for a TS.Flag value ('Germany'), or None."""
    if not isinstance(value, int) or not 0 < value < len(FLAGS):
        return None
    return FLAGS[value][0].replace('_', ' ')


def flag_emoji(code):
    """The flag emoji for an ISO code: two regional indicator letters."""
    return ''.join(chr(0x1F1E6 + ord(letter) - ord('A')) for letter in code.upper())


def flag_text(value):
    """What stands for a flag in a font without flag icons: the code, or the start of
    the country's name where there is no code."""
    code = flag_code(value)
    if code:
        return code
    if not isinstance(value, int) or not 0 < value < len(FLAGS):
        return ''
    name = FLAGS[value][0]
    return TEXT_FLAGS.get(name, name[:3].upper())  # three letters: never taken for an ISO code


